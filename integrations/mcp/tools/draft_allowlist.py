#!/usr/bin/env python3
"""Draft an `allowlist.yaml` from a fork target's own tool registrations.

`integrations/mcp/CLAUDE.md` rule 2: an agent may DRAFT an allowlist for a NEW
fork; a human decides every `requires_confirmation` and every addition to an
existing one. This produces the draft, so the human decision starts from the
real registered names rather than a hand-typed list that drifts.

TWO RULES IT ENFORCES, both from the CAD-02 precedent:

  * **Everything starts `requires_confirmation: true`.** A human downgrading a
    tool after reading it is a decision; a human overlooking one is an accident.
  * **The vendor's own `destructiveHint` / `readOnlyHint` is recorded but NEVER
    obeyed.** It is upstream's claim about upstream's code. It goes in the
    reason line as evidence for the reviewer, prefixed so nobody mistakes it for
    a Solus judgement.

Tools the fabricated-data audit flagged are emitted COMMENTED OUT with the
finding attached — they must not ship, and a silent omission would leave the
reviewer wondering whether the name was simply missed.

    python3 integrations/mcp/tools/draft_allowlist.py <clone> --server solidworks
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from audit_fabricated_tools import audit  # noqa: E402

#: MCP-03 naming bound: `{server}.{tool}` is composed at discovery and the bare
#: name is gated at 128 chars, so the composed length is checked here instead.
MAX_COMPOSED_NAME = 128


def _hints(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """Whatever upstream declared about this tool — untrusted, for the reviewer."""
    claims: list[str] = []
    for dec in node.decorator_list:
        rendered = ast.unparse(dec)
        for hint in ("readOnlyHint", "destructiveHint", "idempotentHint"):
            for polarity in ("True", "False"):
                if f"'{hint}': {polarity}" in rendered or f'"{hint}": {polarity}' in rendered:
                    claims.append(f"{hint}={polarity}")
        if "cost='mutate'" in rendered or 'cost="mutate"' in rendered:
            claims.append("cost=mutate")
        if "cost='read'" in rendered or 'cost="read"' in rendered:
            claims.append("cost=read")
    return ", ".join(dict.fromkeys(claims))


def collect(root: Path) -> list[tuple[str, str, str]]:
    """(name, first docstring line, upstream hints) for every registered tool."""
    found: dict[str, tuple[str, str, str]] = {}
    for path in sorted(root.rglob("*.py")):
        rel = f"/{path.relative_to(root)}"
        if "/tests/" in rel or path.name.startswith("test_"):
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
                continue
            if not any("tool" in ast.unparse(d) for d in node.decorator_list):
                continue
            summary = " ".join((ast.get_docstring(node) or "").split())[:110]
            found.setdefault(node.name, (node.name, summary, _hints(node)))
    return sorted(found.values())


def render(server: str, tools: list[tuple[str, str, str]], flagged: dict[str, str]) -> str:
    lines = [
        f"# DRAFT — generated by integrations/mcp/tools/draft_allowlist.py for {server!r}.",
        "# Every requires_confirmation below is the SAFE DEFAULT, not a decision.",
        "# A human reads each tool and downgrades the ones that only read.",
        "",
        f"server: {server}",
        "tools:",
    ]
    for name, summary, hints in tools:
        composed = len(server) + 1 + len(name)
        if name in flagged:
            lines += [
                f"  # EXCLUDED — fabricated-data audit: {flagged[name]}",
                f"  # - name: {name}",
                "",
            ]
            continue
        if composed > MAX_COMPOSED_NAME:
            lines += [f"  # EXCLUDED — composed name is {composed} chars (max {MAX_COMPOSED_NAME})"]
            continue
        lines += [
            f"  - name: {name}",
            "    requires_confirmation: true # REVIEW: false only if this ONLY reads",
            # json.dumps: a docstring may contain a colon, which unquoted is a
            # YAML mapping and silently corrupts the file.
            "    reason: "
            + json.dumps(
                "TODO Solus-authored. Upstream claims "
                f"[{hints or 'nothing'}]: {summary or '(no docstring)'}"
            ),
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("clone", type=Path)
    parser.add_argument("--server", required=True)
    args = parser.parse_args(argv[1:])

    if not args.clone.is_dir():
        print(f"not a directory: {args.clone}", file=sys.stderr)
        return 2

    report = audit(args.clone)
    flagged = {f.tool: f.kind for f in report.findings}
    tools = collect(args.clone)
    print(render(args.server, tools, flagged), end="")
    print(
        f"\n# {len(tools)} registered, {len(flagged)} excluded by the audit, "
        f"{len(tools) - len(flagged)} awaiting human review.",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
